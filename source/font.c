static uint8_t table[128][7];
/* note : codes 1-4 = symboles des boutons PlayStation */
static int ready;

static void build(void)
{
    int i, r, c;
    for (i = 0; glyphs[i].c; i++) {
        unsigned char ch = (unsigned char)glyphs[i].c;
        if (ch == ' ') continue;
        for (r = 0; r < 7; r++) {
            uint8_t bits = 0;
            for (c = 0; c < 5; c++) if (glyphs[i].rows[r * 5 + c] == '#') bits |= (uint8_t)(1 << (4 - c));
            table[ch][r] = bits;
        }
    }
    ready = 1;
}

const uint8_t *font_glyph(int ch)
{
    if (!ready) build();
    if (ch < 0 || ch >= 128) ch = '?';
    if (ch >= 'a' && ch <= 'z') ch -= 32;
    return table[ch];
}
